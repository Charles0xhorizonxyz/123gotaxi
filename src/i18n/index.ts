export const STRINGS: Record<Language, Strings> = { en, fr, tr, de, es, ru: ruStrings };

function isLanguage(value: unknown): value is Language {
  return typeof value === 'string' && value in LANGUAGES;
}

/** The saved choice; otherwise the first of the phone's languages we have; otherwise English. */
export function pickLanguage(saved: string | null, phoneLanguages: readonly string[]): Language {
  if (isLanguage(saved)) return saved;
  for (const tag of phoneLanguages) {
    const base = tag.toLowerCase().split('-')[0];
    if (isLanguage(base)) return base;
  }
  return 'en';
}

function savedLanguage(): string | null {
  try {
    return globalThis.localStorage?.getItem(LANGUAGE_KEY) ?? null;
  } catch {
    return null;
  }
}

export const language: Language = pickLanguage(
  savedLanguage(),
  globalThis.navigator?.languages ?? [globalThis.navigator?.language ?? 'en'],
);

/** This page's words. */
export const t: Strings = STRINGS[language];

/** Switch language: remember it and reload, so every part of the page speaks it. */
export function setLanguage(next: Language): void {
  try {
    localStorage.setItem(LANGUAGE_KEY, next);
  } catch {
    // Not saved: it still applies for this visit.
  }
  location.reload();
}
